import type { ToolEffect } from '../assistant/tools/registry.ts';

/**
 * Защита от выдуманных действий при своём делегировании: модель не может сообщить «поставил», «записал», «отправил»,
 * если в этом делегировании не было успешного вызова инструмента, который что-то меняет (звонок 22.09.2026: Gemini
 * «поставил» напоминание без инструмента; 23.09.2026: «Считаю на маке» без computer_start, теперь work_start).
 * С 26.09.2026 окончательно решает Jev (delegation/client.ts, #claims), а слова здесь — широкий предфильтр (ответ без них
 * Jev не ждёт) и запасное правило, когда Jev нет или он не ответил вовремя.
 */

// Утверждения о сделанном или обещание сделать от первого лица; «не поставил», «не могу поставить» и «не было создано» не
// считаются. С 26.09.2026 и краткие причастия («Напоминание создано», «Записано.») и начало дела («Запускаю работу», «Уже ищу
// на маке», «Передал Клоду»): до этого Jev их не видел. «Считаю» — и ход работы («Считаю на маке»), и мнение («Я считаю,
// лучше второй»): мнение начинается с «я», его не ловим. «Наберу», «звоню» — звонок 26.09.2026: «Сейчас наберу.» без
// callback_schedule прошло, и Волна пообещала перезвонить, не записав перезвон.
const CLAIM = new RegExp('(?<![Нн]е\\s)(?<![Нн]е\\s(?:был[оаи]?|будет|будут)\\s)(?<!чтобы\\s(?:я\\s)?)(?<![а-яё])(' + [
  'ставлю|поставил[аи]?|постави(?:л|ла)|поставлю|созда(?:л|ла|м|ю)|записал[аи]?|запишу|записываю|запомнил[аи]?|запомню',
  'добавил[аи]?|добавлю|добавляю|отправил[аи]?|отправлю|отправляю|отметил[аи]?|отмечу|удалил[аи]?|удалю|сохранил[аи]?|сохраню',
  'перенес(?:ла|ёл|л)?|перенёс|перенесу|напомню|заказал[аи]?|закажу|перевёл|перевел[аи]?|переведу|назначил[аи]?|назначу',
  'открыл[аи]?|открою|открываю|запустил[аи]?|запущу|запускаю|посчитал[аи]?|посчитаю|(?<![Яя]\\s)считаю|сделал[аи]?|сделаю|делаю',
  'ищу|займусь|разберусь|передал[аи]?|передам|передаю|перезвоню|перезваниваю|позвоню|звоню|наберу|набер[её]м|набираю|включил[аи]?|включу|отменил[аи]?|отменю|готово',
  // Краткие причастия: «Напоминание поставлено», «Записано», «Добавлено в календарь».
  '(?:по)?ставлен[оаы]?|создан[оаы]?|записан[оаы]?|добавлен[оаы]?|отправлен[оаы]?|сохран[её]н[оаы]?|удал[её]н[оаы]?',
  'назначен[оаы]?|запущен[оаы]?|отмечен[оаы]?|перенес[её]н[оаы]?|передан[оаы]?|включ[её]н[оаы]?|отмен[её]н[оаы]?|заказан[оаы]?|сделан[оаы]?'
].join('|') + ')(?![а-яё])', 'i');

/** Заявляет ли текст о действии. */
export function claimsAction(text: string): boolean {
  // Вопросы («Записать?», «Хотите, чтобы я записал?») не заявления.
  return text.split(/(?<=[.!?…])\s+/).some(sentence => !sentence.trim().endsWith('?') && CLAIM.test(sentence));
}

/**
 * Подтверждает ли вызов действие: инструмент не читающий (по `effect` из реестра) и без ошибки. До 25.09.2026 здесь был
 * свой список читающих; он отстал, и после techcard_read ответ без инструмента «Готово.» сошёл за сделанное.
 */
export function confirmsAction(effect: ToolEffect | undefined, output: string): boolean {
  return effect !== undefined && effect !== 'read' && !output.trimStart().startsWith('{"error"');
}

export const HONESTY_RETRY = 'Служебное сообщение ядра, не от пользователя; о нём пользователю не говори. Проверка ядра: в ответе ты сообщаешь о действии, но инструмент для него не вызван или вернул ошибку. Если действие нужно и инструмент есть, вызови его. Если инструмента нет или он не сработал, честно скажи пользователю, что сделать это не получилось. Ничего не выдумывай.';
export const HONESTY_FALLBACK = 'Бэкенд не выполнил действие. Честно скажи пользователю, что сделать это сейчас не получилось.';

/** Вызов инструмента в проходе делегирования (как его видит Jev, jev/questions.ts). */
export interface CallNote { tool: string; effect: string; ok: boolean }

/**
 * Неудачные меняющие вызовы, которые не исправлены последующими успехами того же инструмента: неудача считается
 * исправленной, только если успехов после неё хватает на все неудачи (два напоминания упали, одно повторилось удачно —
 * одно осталось несделанным). Повтор после ошибки не частичный успех.
 */
export function unrecovered(calls: readonly CallNote[]): CallNote[] {
  const failed = new Map<string, CallNote[]>();
  for (const call of calls) {
    if (call.effect === 'read') continue;
    const open = failed.get(call.tool) ?? [];
    if (!call.ok) open.push(call);
    else open.shift();
    failed.set(call.tool, open);
  }
  return [...failed.values()].flat();
}

/**
 * Решение по словам, когда Jev нет, он ошибся или опоздал: заявление ловится в ответе вовсе без вызовов или после
 * неудачного меняющего вызова без единого успешного («Отправил» после упавшей отправки). После читающих вызовов не ловится:
 * 25.09.2026 «Меня сделал Андрей» после about_wave сошло за действие. Частичный успех без Jev пропускается.
 */
export function claimsByWords(calls: readonly CallNote[], acted: boolean): boolean {
  return calls.length === 0 || (!acted && unrecovered(calls).length > 0);
}

/** Как назвать сделанное для голосовой модели: имя инструмента она могла бы произнести вслух. */
const DONE_TITLES: Record<string, string> = {
  create_reminder: 'напоминание', complete_reminder: 'отметка напоминания', create_event: 'событие в календаре',
  remember: 'запись в память', forget: 'удаление из памяти', work_start: 'запуск работы', work_send: 'сообщение агенту',
  work_add: 'дополнение к работе', work_answer: 'ответ агенту', tasks_call_back: 'перезвон по готовности', task_cancel: 'отмена задания',
  callback_schedule: 'перезвон по времени', callback_cancel: 'отмена перезвона',
  schedule_create: 'повторяющееся задание', schedule_delete: 'удаление повторяющегося задания',
  techcard_write: 'правка техкарты', techcard_delete: 'удаление техкарты', techcard_create: 'новая техкарта', end_call: 'завершение звонка'
};

/**
 * Честный отказ после повторного заявления о несделанном. При частичном успехе не «ничего не получилось»: называет
 * сделанное по-человечески (DONE_TITLES; без аргументов: их текст в замеры и заметки не нужен) и что часть не вышла.
 */
export function honestyFallback(calls: readonly CallNote[]): string {
  const done = calls.filter(call => call.ok && call.effect !== 'read' && call.effect !== 'unknown');
  if (!done.length) return HONESTY_FALLBACK;
  const titles = [...new Set(done.map(call => DONE_TITLES[call.tool]).filter(Boolean))];
  const what = titles.length ? `: получилось ${titles.join(', ')}` : '';
  return `Бэкенд сделал только часть${what}; остальное не получилось. Скажи пользователю своими словами, что сделано, и честно, что остальное сделать не получилось; названия инструментов не произноси.`;
}
